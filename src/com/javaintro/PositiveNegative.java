package com.javaintro;

public class PositiveNegative {

	public static void main(String[] args) {

		int num = -10;

		if (num > 0) {
			System.out.println("Positive:" + num);
		}
		
		else if (num < 0) {
			System.out.println("Negative:" + num);
		}
		
		else {
			System.out.println("Zero:" + num);
		}
	}
   }
